let direction = "south";
switch (direction) {
case "north": 
console.log("You head towards the mountains");
break;
case "south":
console.log("You travel to the sea");
break;
case "east": 
console.log("You enter the forest");
break;
case "west":
console.log("You approach the desert");
break;
default: 
console.log("Invalid direction!"); 
}


