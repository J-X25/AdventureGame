// Switch Statements:

// Menu Selection Example:
let menuSelection = 3;

switch (menuSelection) {   
    case 1:
        console.log("Selected: View Profile");
        break;  
    case 2:
        console.log("Selected: Account Settings");
        break;
    case 3:
        console.log("Selected: Logout");
        break;
    default: 
        console.log("Invalid selection. Please choose 1-3.");   
}    